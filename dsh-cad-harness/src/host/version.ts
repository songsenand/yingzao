// Version store: every generation round persists code, STL, renders, and a
// manifest entry under <projectRoot>/versions/vNNN (projectRoot =
// $DSH_HOME/cad/<project key>, see project.ts).
//
// A version is the unit of "geometry that was validated", not "a SCAD file".
// Since imports landed, a version may have NO source code at all: a version
// records where its geometry came from via `source`, and `model.scad` is
// written only when there is one. Everything downstream reads `model.stl`,
// which is why an imported part is a first-class citizen rather than a special
// case. Absent `source` means `generated` — the pre-import corpora stay valid
// with no migration.

import { access, mkdir, readdir, readFile, rename, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/**
 * Where a version's geometry came from.
 *
 * `imported` carries the fingerprint of the file that was read, because "which
 * bearing is this" is a question a human will ask months later, and a filename
 * alone cannot answer it. `unit`/`scale` are the caller's *declaration*, stored
 * verbatim: an STL carries no unit, and guessing one is how a part silently
 * ends up 25.4x too big.
 */
export type VersionSource =
  | { kind: 'generated' }
  | {
    kind: 'imported';
    /** Absolute path the bytes were read from at import time. */
    file: string;
    sha256: string;
    bytes: number;
    format: string;
    unit: string;
    scale: number;
    /** What welding changed, in words ("12 duplicate vertices merged"). */
    repaired: string[];
    at: string;
  }
  | {
    /**
     * A union of other parts at their assembly placements (`merge_parts`).
     * Recorded because the merged body is a DERIVED artifact: without the list
     * of what went into it, nothing can say whether it is still current.
     */
    kind: 'merged';
    from: { name: string; versionId: string | null }[];
    at: string;
  };

export interface VersionManifestEntry {
  id: string;
  timestamp: string;
  userIntent: string;
  /** Previous version of the SAME part (null = first version of that part). */
  parentVersion: string | null;
  /** The part this version belongs to (`parts/manifest.json` in the same project). */
  partId?: string;
  status: 'draft' | 'approved' | 'rejected';
  /** Absent = generated by this harness (the only kind before imports existed). */
  source?: VersionSource;
  /**
   * Whether the stored mesh is a closed solid. Absent = true. A version may be
   * stored with `false` only when the caller explicitly allowed it, and every
   * consumer that needs a solid must say so rather than measure a broken mesh.
   */
  solid?: boolean;
  /**
   * Set when this row was REBUILT from the `versions/` directory because the index
   * was missing or unreadable. Its intent/parent/part are unknowable in that case, and
   * saying so is the point: a recovered row must not look like a normal one.
   */
  recovered?: boolean;
}

export interface VersionStore {
  root: string;
}

export function openVersionStore(root: string): VersionStore {
  return { root };
}

function versionsDir(store: VersionStore): string {
  return join(store.root, 'versions');
}

/** Next version id: v001, v002, … based on existing directories. */
async function nextVersionId(store: VersionStore): Promise<string> {
  await mkdir(versionsDir(store), { recursive: true });
  const entries = await readdir(versionsDir(store));
  const max = entries.reduce((m, name) => {
    const match = /^v(\d{3,})$/.exec(name);
    return match ? Math.max(m, parseInt(match[1]!, 10)) : m;
  }, 0);
  return `v${String(max + 1).padStart(3, '0')}`;
}

/**
 * Read the version index, repairing it from `versions/` when it is missing or broken.
 *
 * WHY: the directory is the durable record (each `vNNN/` carries model.scad/stl, its
 * renders and datums). The index is an optimisation over it. Treating invalid JSON as an
 * empty index made a torn write look like "this project has no versions", and the next
 * `saveVersion` wrote that emptiness back — losing intent/parent/part for every version
 * while the directories sat there intact (2026-10-23 audit, FIX-C3).
 *
 * Recovered rows say so (`recovered: true`) and keep a null parent/part: inventing them
 * would be worse than admitting the loss. The file itself is NOT rewritten on read (a
 * read must not mutate); the next `saveVersion` persists the healed index.
 */
export async function readManifest(store: VersionStore): Promise<{ versions: VersionManifestEntry[] }> {
  let raw: string;
  try {
    raw = await readFile(join(store.root, 'manifest.json'), 'utf8');
  } catch {
    return { versions: await recoverFromDirectories(store) };
  }
  try {
    const parsed = JSON.parse(raw) as { versions?: VersionManifestEntry[] };
    const versions = Array.isArray(parsed?.versions) ? parsed.versions : [];
    // An index that is valid JSON but lost rows is healed too: a version directory the
    // index does not mention is a version the panel and every tool would refuse to see.
    const known = new Set(versions.map((v) => v.id));
    const missing = (await listVersionDirs(store)).filter((id) => !known.has(id));
    if (missing.length === 0) return { versions };
    const recovered = await recoverFromDirectories(store, versions);
    return { versions: recovered };
  } catch {
    return { versions: await recoverFromDirectories(store) };
  }
}

/** Version ids present on disk, in numeric order. */
async function listVersionDirs(store: VersionStore): Promise<string[]> {
  try {
    return (await readdir(versionsDir(store)))
      .filter((name) => /^v\d{3,}$/.test(name))
      .sort((a, b) => parseInt(a.slice(1), 10) - parseInt(b.slice(1), 10));
  } catch {
    return [];
  }
}

/**
 * Rebuild index rows from the version directories. `keep` (an already-parsed index) is
 * preserved for the ids it still knows; only the unknown ones are reconstructed.
 */
async function recoverFromDirectories(
  store: VersionStore,
  keep: VersionManifestEntry[] = [],
): Promise<VersionManifestEntry[]> {
  const byId = new Map(keep.map((v) => [v.id, v]));
  for (const id of await listVersionDirs(store)) {
    if (byId.has(id)) continue;
    const dir = join(versionsDir(store), id);
    let timestamp = new Date(0).toISOString();
    try { timestamp = (await stat(dir)).mtime.toISOString(); } catch { /* keep epoch */ }
    // Sidecars carry what the index lost, when the version was imported or merged.
    let userIntent = 'unknown (recovered from the directory)';
    let source: VersionSource | undefined;
    for (const [file, kind] of [['import.json', 'imported'], ['source.json', 'merged']] as const) {
      try {
        const meta = JSON.parse(await readFile(join(dir, file), 'utf8')) as Record<string, unknown>;
        if (typeof meta.userIntent === 'string') userIntent = meta.userIntent;
        if (meta.kind === kind) source = meta as unknown as VersionSource;
        if (typeof meta.parentVersion === 'string') { /* parent is part-relative; keep null */ }
        break;
      } catch { /* no sidecar */ }
    }
    byId.set(id, {
      id, timestamp, userIntent, parentVersion: null, status: 'draft',
      ...(source ? { source } : {}),
      recovered: true,
    });
  }
  return [...byId.values()].sort((a, b) => parseInt(a.id.slice(1), 10) - parseInt(b.id.slice(1), 10));
}

/**
 * Compare the index with the directories WITHOUT healing either side.
 *
 * Used by the acceptance (and available to a future audit finding): "the index and the
 * files agree" is a property DESIGN §6.8 claims and nothing checked.
 */
export async function diagnoseManifest(store: VersionStore): Promise<{
  onDisk: string[];
  inIndex: string[];
  onlyOnDisk: string[];
  onlyInIndex: string[];
  parseError: string | null;
}> {
  const onDisk = await listVersionDirs(store);
  let inIndex: string[] = [];
  let parseError: string | null = null;
  try {
    const parsed = JSON.parse(await readFile(join(store.root, 'manifest.json'), 'utf8')) as { versions?: { id: string }[] };
    inIndex = (parsed?.versions ?? []).map((v) => v.id);
  } catch (e) {
    parseError = String((e as Error)?.message ?? e);
  }
  return {
    onDisk,
    inIndex,
    onlyOnDisk: onDisk.filter((id) => !inIndex.includes(id)),
    onlyInIndex: inIndex.filter((id) => !onDisk.includes(id)),
    parseError,
  };
}

export interface SaveVersionInput {
  /** Absent for an imported version — there is no source code to persist. */
  scadCode?: string;
  stl?: Uint8Array;
  renders?: { view: string; png: Uint8Array }[];
  userIntent: string;
  parentVersion?: string | null;
  /** Part identity; omitted only for legacy callers that have none. */
  partId?: string;
  /** Datum anchor points (name → world coordinate) declared in the code. */
  datums?: { name: string; point: [number, number, number] }[];
  /** Axes/planes/cylinders (assembly manifest v1); points also accepted here. */
  datumSet?: import('./compile.ts').DatumSet;
  /** Where the geometry came from; absent = generated by this harness. */
  source?: VersionSource;
  /** Whether the stored mesh is a closed solid (absent = true). */
  solid?: boolean;
}

/** Persist one generation round; returns the created version id. */
export async function saveVersion(store: VersionStore, input: SaveVersionInput): Promise<string> {
  const id = await nextVersionId(store);
  // Read the index BEFORE this version's directory exists. The loader heals itself from
  // the directories, so creating the directory first made it "recover" the version that
  // was about to be appended — and the index ended up with that id twice
  // (caught by accept-version-index).
  const manifest = await readManifest(store);
  const dir = join(versionsDir(store), id);
  await mkdir(dir, { recursive: true });
  if (input.scadCode !== undefined) await writeFile(join(dir, 'model.scad'), input.scadCode, 'utf8');
  if (input.stl) await writeFile(join(dir, 'model.stl'), input.stl);
  const datumSet = mergeDatumSet(input.datums, input.datumSet);
  if (datumSet) {
    await writeFile(join(dir, 'datums.json'), JSON.stringify(datumSet, null, 2));
  }
  // The provenance record sits next to datums.json, so a human (or a script
  // with no knowledge of the manifest schema) can answer "where did this come
  // from" from the version directory alone.
  if (input.source && input.source.kind === 'imported') {
    await writeFile(join(dir, 'import.json'), JSON.stringify({
      ...input.source,
      versionId: id,
      userIntent: input.userIntent,
      parentVersion: input.parentVersion ?? null,
      solid: input.solid ?? true,
    }, null, 2));
  }
  // Derived geometry gets the same treatment under its own name: a merged body
  // has no source code to re-read, so the list of what it was made of is the
  // only thing that can tell a later reader whether it is still current.
  if (input.source && input.source.kind === 'merged') {
    await writeFile(join(dir, 'source.json'), JSON.stringify({
      ...input.source,
      versionId: id,
      userIntent: input.userIntent,
      solid: input.solid ?? true,
    }, null, 2));
  }
  for (const r of input.renders ?? []) {
    await writeFile(join(dir, `render_${r.view}.png`), r.png);
  }
  manifest.versions.push({
    id,
    timestamp: new Date().toISOString(),
    userIntent: input.userIntent,
    parentVersion: input.parentVersion ?? null,
    ...(input.partId ? { partId: input.partId } : {}),
    status: 'draft',
    ...(input.source ? { source: input.source } : {}),
    ...(input.solid === false ? { solid: false } : {}),
  });
  // tmp + rename, like `runs.ts` and `parts.ts`. A torn write here used to lose the
  // WHOLE history: `readManifest` treated invalid JSON as an empty index, and the next
  // save rewrote it with a single row (2026-10-23 audit, FIX-C3).
  await mkdir(store.root, { recursive: true });
  const tmp = join(store.root, 'manifest.json.tmp');
  await writeFile(tmp, JSON.stringify(manifest, null, 2));
  await rename(tmp, join(store.root, 'manifest.json'));
  return id;
}

/** One version's manifest entry, or null. */
export async function readVersionEntry(store: VersionStore, id: string): Promise<VersionManifestEntry | null> {
  return (await readManifest(store)).versions.find((v) => v.id === id) ?? null;
}

/**
 * Point datum anchors of one version, by name.
 *
 * `datums.json` has two historical shapes and both are still on disk: the
 * extended `DatumSet` written since assembly interfaces landed
 * (`{points, axes, planes, cylinders}`) and the legacy plain array of
 * `{name, point}`. Callers that only want points read through here, so nobody
 * has to guess — reading only one shape silently reported "declared: none" for
 * every version written in the other.
 */
export async function readVersionDatumPoints(
  store: VersionStore,
  id: string,
): Promise<Record<string, [number, number, number]>> {
  try {
    const raw = JSON.parse(await readFile(join(versionsDir(store), id, 'datums.json'), 'utf8')) as unknown;
    const list = (Array.isArray(raw)
      ? raw
      : (raw as { points?: { name: string; point: [number, number, number] }[] })?.points ?? []);
    return Object.fromEntries(list.map((d) => [d.name, d.point]));
  } catch {
    return {};
  }
}

/** List version ids newest-first. */
export async function listVersions(store: VersionStore): Promise<VersionManifestEntry[]> {
  return (await readManifest(store)).versions.slice().reverse();
}

/**
 * Does the version DIRECTORY exist, even if the index lost track of it?
 *
 * `manifest.json` is the index, but a version directory is the artifact — the
 * two can disagree (an older corpus, a hand-copied store). Callers that only
 * need "is there something to read/write here" ask this instead of failing on a
 * missing index row.
 */
export async function versionExists(store: VersionStore, id: string): Promise<boolean> {
  try { await access(join(versionsDir(store), id)); return true; } catch { return false; }
}

/** Every datum name in a set, in a stable order. */
export function datumNames(set: import('./compile.ts').DatumSet): string[] {
  return [
    ...set.points.map((d) => `point:${d.name}`),
    ...set.axes.map((d) => `axis:${d.name}`),
    ...set.planes.map((d) => `plane:${d.name}`),
    ...set.cylinders.map((d) => `cylinder:${d.name}`),
  ];
}

/** Union two datum sets; `incoming` wins on a name collision. */
export function unionDatumSets(
  base: import('./compile.ts').DatumSet,
  incoming: import('./compile.ts').DatumSet,
): import('./compile.ts').DatumSet {
  const namesIn = new Set(incoming.points.map((d) => d.name));
  const namesInAxes = new Set(incoming.axes.map((d) => d.name));
  const namesInPlanes = new Set(incoming.planes.map((d) => d.name));
  const namesInCyl = new Set(incoming.cylinders.map((d) => d.name));
  return {
    points: [...base.points.filter((d) => !namesIn.has(d.name)), ...incoming.points],
    axes: [...base.axes.filter((d) => !namesInAxes.has(d.name)), ...incoming.axes],
    planes: [...base.planes.filter((d) => !namesInPlanes.has(d.name)), ...incoming.planes],
    cylinders: [...base.cylinders.filter((d) => !namesInCyl.has(d.name)), ...incoming.cylinders],
  };
}

/**
 * Overwrite a version's datums.json, in place, WITHOUT creating a version.
 *
 * Datums do not affect the mesh, so "I forgot an anchor" used to cost a whole
 * new version whose only change was metadata — the microscope2 corpus carries
 * three of them (v006, v007, v037), each with 4 render images, drowning the
 * versions that were actual design changes. Metadata gets a metadata-sized edit.
 */
export async function writeVersionDatums(
  store: VersionStore,
  versionId: string,
  set: import('./compile.ts').DatumSet,
): Promise<void> {
  const dir = join(versionsDir(store), versionId);
  await mkdir(dir, { recursive: true });
  await writeFile(join(dir, 'datums.json'), JSON.stringify(set, null, 2));
}

/**
 * Merge legacy points + new datumSet into one persisted structure. Returns
 * null when neither carries any anchor (older versions may have none).
 */
function mergeDatumSet(
  points: SaveVersionInput['datums'],
  set: SaveVersionInput['datumSet'],
): import('./compile.ts').DatumSet | null {
  const merged: import('./compile.ts').DatumSet = {
    points: points ?? set?.points ?? [],
    axes: set?.axes ?? [],
    planes: set?.planes ?? [],
    cylinders: set?.cylinders ?? [],
  };
  const total = merged.points.length + merged.axes.length + merged.planes.length + merged.cylinders.length;
  return total > 0 ? merged : null;
}

/**
 * Read a version's datum set. Accepts both the legacy array format
 * (points only) and the v1 record format {points, axes, planes, cylinders}.
 */
export async function readVersionDatums(store: VersionStore, versionId: string): Promise<import('./compile.ts').DatumSet> {
  try {
    const raw = JSON.parse(await readFile(join(versionsDir(store), versionId, 'datums.json'), 'utf8'));
    if (Array.isArray(raw)) return { points: raw, axes: [], planes: [], cylinders: [] };
    return {
      points: raw.points ?? [],
      axes: raw.axes ?? [],
      planes: raw.planes ?? [],
      cylinders: raw.cylinders ?? [],
    };
  } catch {
    return { points: [], axes: [], planes: [], cylinders: [] };
  }
}
